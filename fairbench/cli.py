"""Command line: ``python -m fairbench <command>`` (see docs/EXPERIMENTS.md).

    synth            render the synthetic stand-in dataset (pipeline testing)
    import-kubric    build manifest.json from Kubric renders
    validate         check a dataset; print the score constants (E_ceil, E_ref, ...)
    plan             list jobs and estimated cost (no API calls)
    generate         run generation (``--dry-run`` first!)
    import-outputs   bring in videos generated by hand
    score            track + score one model's run (or a baseline)
    report           compare scored models; all aggregation candidates
    sanity           synth + mock models + baselines + score + report, end to end
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

from .config import config_hash, load_configs, model_entries, resolve


def _ds(args, cfg):
    from .manifest import Dataset

    path = args.dataset or cfg["dataset"].get("manifest")
    if not path:
        sys.exit("no dataset: pass --dataset or set 'manifest' in configs/dataset.yaml")
    return Dataset.load(resolve(path))


def _run_dir(args, cfg) -> Path:
    return resolve(cfg["dataset"].get("runs_dir", "runs")) / args.run


def _calibration(ds, mcfg):
    from .metrics.calibration import load_or_calibrate

    return load_or_calibrate(ds, noise_px=float(mcfg.get("noise_px", 0.3)), n_mc=int(mcfg.get("calibration_mc", 50)),
                             median_k=int(mcfg.get("median_k", 5)), full_visible=float(mcfg.get("visible_full", 0.99)))


def _tracker(name, mcfg):
    from .tracking.base import get_tracker

    tcfg = (mcfg.get("tracking") or {}).get(name, {}) or {}
    if name == "sam2" and tcfg.get("checkpoint"):
        tcfg = {**tcfg, "checkpoint": str(resolve(tcfg["checkpoint"]))}
    return get_tracker(name, **tcfg)


# ---------------------------------------------------------------------------- commands
def cmd_synth(args, cfg):
    from .synthetic import build_synthetic_dataset

    w, h = map(int, args.res.lower().split("x"))
    ds = build_synthetic_dataset(resolve(args.out), width=w, height=h, ss=args.ss)
    print(f"wrote {len(ds.clips)} clips + manifest to {ds.root}")


def cmd_import_kubric(args, cfg):
    from .kubric_import import import_kubric

    import_kubric(resolve(args.src), resolve(args.out), mapping=args.mapping)


def cmd_validate(args, cfg):
    from .validate import validate

    ds = _ds(args, cfg)
    tracker = None if args.no_track else _tracker(args.tracker, cfg["metrics"])
    rep = validate(ds, cfg["metrics"], tracker=tracker, track_reference=not args.no_track)
    print(json.dumps(rep, indent=2, default=str))


def cmd_plan(args, cfg):
    from .generate import check_model_fits, plan_jobs

    ds = _ds(args, cfg)
    models = model_entries(cfg["models"])
    names = args.models or [n for n, m in models.items() if m.get("enabled")]
    total = 0.0
    print(f"{'model':28s} {'jobs':>5s} {'$/gen':>7s} {'total $':>8s}  notes")
    for n in names:
        if n not in models:
            sys.exit(f"unknown model {n}")
        jobs = plan_jobs(ds, _run_dir(args, cfg), models, cfg["generation"], [n], samples=args.samples)
        cost = sum(j.cost_usd for j in jobs)
        total += cost
        notes = "; ".join(check_model_fits(ds, n, models[n])) or models[n].get("notes", "")
        print(f"{n:28s} {len(jobs):5d} {models[n].get('cost_per_generation_usd') or 0:7.2f} {cost:8.2f}  {notes}")
    print(f"{'TOTAL':28s} {'':5s} {'':7s} {total:8.2f}")


def cmd_generate(args, cfg):
    from .generate import check_model_fits, plan_jobs, run_jobs

    ds = _ds(args, cfg)
    models = model_entries(cfg["models"])
    names = args.models or [n for n, m in models.items() if m.get("enabled")]
    if not names:
        sys.exit("no models selected: pass --models or set enabled: true in configs/models.yaml")
    for n in names:
        probs = check_model_fits(ds, n, models[n])
        if probs and not args.force:
            sys.exit("refusing to run (use --force to override):\n  " + "\n  ".join(probs))
    run_dir = _run_dir(args, cfg)
    jobs = plan_jobs(ds, run_dir, models, cfg["generation"], names, clips=args.clips, samples=args.samples)
    (run_dir).mkdir(parents=True, exist_ok=True)
    (run_dir / "run_config.json").write_text(json.dumps(
        {"generation": cfg["generation"], "models": {n: models[n] for n in names},
         "config_hash": config_hash([cfg["generation"], {n: models[n] for n in names}])}, indent=2, default=str))
    res = run_jobs(ds, run_dir, jobs, models, cfg["generation"], budget_usd=args.max_usd, dry_run=args.dry_run)
    print(json.dumps(res, indent=2))


def cmd_import_outputs(args, cfg):
    from .generate import import_outputs

    ds = _ds(args, cfg)
    import_outputs(ds, _run_dir(args, cfg), args.model, resolve(args.dir))


def cmd_score(args, cfg):
    from .baselines import BASELINES, baseline_tracks
    from .score import collect_tracks, score_tracks, write_scores

    ds = _ds(args, cfg)
    mcfg = cfg["metrics"]
    cal = _calibration(ds, mcfg)
    run_dir = _run_dir(args, cfg)
    methods = tuple(args.methods.split(",")) if args.methods else tuple(mcfg.get("dynamical_methods", ["lsq", "pinn"]))
    if args.model.startswith("baseline:"):
        name = args.model.split(":", 1)[1]
        if name not in BASELINES:
            sys.exit(f"unknown baseline {name}; choose from {BASELINES}")
        tracks = baseline_tracks(ds, name, noise_px=float(mcfg.get("baseline_noise_px", 0.3)),
                                 samples=int(mcfg.get("baseline_samples", 1)))
        out = run_dir / "baselines" / name / "scores"
    else:
        tname = args.tracker or (mcfg.get("tracking") or {}).get("tracker", "sam2")
        tracker = _tracker(tname, mcfg)
        models = model_entries(cfg["models"])
        align_cfg = (models.get(args.model, {}) or {}).get("align", {})
        tracks = collect_tracks(ds, run_dir, args.model, tracker, mcfg, align_cfg, retrack=args.retrack)
        if not tracks:
            sys.exit(f"no videos under {run_dir / args.model}")
        out = run_dir / args.model / "scores"
    gen, grp, summary = score_tracks(ds, tracks, cal, mcfg, methods=methods)
    write_scores(out, gen, grp, summary, {"model": args.model, "calibration": cal["groups"],
                                          "metrics_config_hash": config_hash(mcfg)})
    if args.plots:
        from .report import plot_tracks

        plot_tracks(ds, tracks, args.model.replace(":", "_"), out / "plots")
    print(f"scores written to {out}")
    for g, v in summary["groups"].items():
        print(f"  {g:15s} R={v['S_rob']:.3f}  P={v['S_plaus']:.3f}  F={v['S_ref']:.3f}  "
              f"(raw {v['rob_raw_m'] * 1000:.1f} mm, ref err {v['ref_err_m'] * 1000:.1f} mm)")


def cmd_report(args, cfg):
    from .report import load_summaries, write_report

    run_dir = _run_dir(args, cfg)
    dirs = {}
    for m in args.models:
        if m.startswith("baseline:"):
            dirs[m] = run_dir / "baselines" / m.split(":", 1)[1] / "scores"
        else:
            dirs[m] = run_dir / m / "scores"
    summ = load_summaries(dirs)
    p = write_report(summ, resolve(args.out) if args.out else run_dir / "report",
                     baselines=tuple(m for m in summ if m.startswith("baseline:")))
    print(f"report: {p}")


def cmd_sanity(args, cfg):
    from .sanity import run_sanity

    run_sanity(resolve(args.out), res=args.res, quick=args.quick)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="fairbench", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config-dir", default=None)
    ap.add_argument("--set", action="append", default=[], metavar="KEY=VALUE", help="override a config value")
    sub = ap.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("synth")
    s.add_argument("--out", default="data/synthetic")
    s.add_argument("--res", default="640x360")
    s.add_argument("--ss", type=int, default=2)
    s.set_defaults(fn=cmd_synth)

    s = sub.add_parser("import-kubric")
    s.add_argument("--src", required=True, help="folder with one subfolder per clip")
    s.add_argument("--out", required=True)
    s.add_argument("--mapping", default=None, help="JSON file mapping clip ids to Kubric folders")
    s.set_defaults(fn=cmd_import_kubric)

    for name, fn in (("validate", cmd_validate), ("plan", cmd_plan), ("generate", cmd_generate),
                     ("import-outputs", cmd_import_outputs), ("score", cmd_score), ("report", cmd_report)):
        s = sub.add_parser(name)
        s.add_argument("--dataset", default=None, help="manifest.json (default: configs/dataset.yaml)")
        s.add_argument("--run", default="main", help="run name under runs/")
        s.set_defaults(fn=fn)
        if name == "validate":
            s.add_argument("--tracker", default="color")
            s.add_argument("--no-track", action="store_true")
        if name in ("plan", "generate"):
            s.add_argument("--models", nargs="*", default=None)
            s.add_argument("--samples", type=int, default=None)
        if name == "generate":
            s.add_argument("--clips", nargs="*", default=None)
            s.add_argument("--dry-run", action="store_true")
            s.add_argument("--max-usd", type=float, default=None)
            s.add_argument("--force", action="store_true")
        if name == "import-outputs":
            s.add_argument("--model", required=True)
            s.add_argument("--dir", required=True)
        if name == "score":
            s.add_argument("--model", required=True, help="model name, or baseline:<name>")
            s.add_argument("--tracker", default=None)
            s.add_argument("--methods", default=None, help="dynamical-score methods, e.g. lsq or lsq,pinn")
            s.add_argument("--retrack", action="store_true")
            s.add_argument("--plots", action="store_true")
        if name == "report":
            s.add_argument("--models", nargs="+", required=True)
            s.add_argument("--out", default=None)

    s = sub.add_parser("sanity")
    s.add_argument("--out", default="runs/sanity")
    s.add_argument("--res", default="320x180")
    s.add_argument("--quick", action="store_true")
    s.set_defaults(fn=cmd_sanity)

    args = ap.parse_args(argv)
    cfg = load_configs(args.config_dir, args.set)
    np.set_printoptions(precision=4, suppress=True)
    args.fn(args, cfg)


if __name__ == "__main__":
    main()
